"""Generate the compact OLED emoji font from pinned OpenMoji 17.0 black SVGs.

Requires Pillow and PNGs from rasterize-openmoji.cjs to regenerate data.
Firmware builds use the checked-in .inc without either dependency.
Original artwork and derived bitmap data: CC BY-SA 4.0, OpenMoji contributors.
"""
from pathlib import Path
import argparse
import hashlib
import json
import zipfile
from PIL import Image, ImageChops, ImageFilter

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("archive", type=Path)
parser.add_argument("metadata", type=Path)
parser.add_argument("--color-fallback-archive", type=Path, required=True)
parser.add_argument("--raster-dir", type=Path, required=True, help="72px PNGs rendered from the SVG archive with rasterize-openmoji.cjs")
parser.add_argument("--output", type=Path, default=Path("src/helpers/ui/emoji"))
args = parser.parse_args()
expected = "f127e2cfd5e8fb17c2a5ec6ec73a66c954a83588ffd1d91047988fc6b70f26e8"
assert hashlib.sha256(args.archive.read_bytes()).hexdigest() == expected, "Wrong OpenMoji archive"
color_sha = "59b0cd9f6fe033818fc02585cea42bea9fba5d68a4d3a3639bfe5d5cc3805689"
assert hashlib.sha256(args.color_fallback_archive.read_bytes()).hexdigest() == color_sha, "Wrong color archive"
metadata_sha = "ab181dd523021dfbe2b98a13d96ab384b7b3014d17815261bc267fb39d9a211b"
assert hashlib.sha256(args.metadata.read_bytes()).hexdigest() == metadata_sha, "Wrong OpenMoji metadata"
records = json.loads(args.metadata.read_text(encoding="utf-8"))
glyphs, glyph_ids, sequences = [], {}, {}
with zipfile.ZipFile(args.archive) as archive:
    for record in records:
        if record["group"].startswith("extras-"):
            continue
        key = tuple(int(value, 16) for value in record["hexcode"].split("-")
                    if int(value, 16) not in (0xFE0E, 0xFE0F))
        if key in sequences:
            continue
        assert record["hexcode"] + ".svg" in archive.namelist()
        rgba = Image.open(args.raster_dir / (record["hexcode"] + ".png")).convert("RGBA")
        ink = ImageChops.multiply(ImageChops.invert(rgba.convert("L")), rgba.getchannel("A"))
        bounds = ink.getbbox()
        if not bounds:  # Some enclosed symbols are white-only in the black export.
            ink = rgba.getchannel("A")
            bounds = ink.getbbox()
        assert bounds, record["hexcode"]
        ink = ink.crop(bounds)
        # Preserve thin outlines when reducing the 72px source to ten OLED pixels.
        ink = ink.filter(ImageFilter.MaxFilter(3))
        ink.thumbnail((10, 10), Image.Resampling.LANCZOS)
        canvas = Image.new("L", (10, 10))
        canvas.paste(ink, ((10 - ink.width) // 2, (10 - ink.height) // 2))
        rows = tuple(sum((1 << (9-x)) for x in range(10) if canvas.getpixel((x, y)) >= 80)
                     for y in range(10))
        assert any(rows), record["hexcode"]
        if rows not in glyph_ids:
            glyph_ids[rows] = len(glyphs)
            glyphs.append(rows)
        sequences[key] = glyph_ids[rows]

root = {"children": {}, "glyph": -1, "cp": 0}
for sequence, glyph in sorted(sequences.items()):
    node = root
    for cp in sequence:
        node = node["children"].setdefault(cp, {"children": {}, "glyph": -1, "cp": cp})
    node["glyph"] = glyph
nodes = [root]
for node in nodes:
    node["first"] = len(nodes)
    nodes.extend(child for _, child in sorted(node["children"].items()))
assert len(nodes) < 65536 and len(glyphs) < 32768
output = ["// Generated by bin/generate-superbase-emoji.py; OpenMoji 17.0, CC BY-SA 4.0.",
          "// See README.md and LICENSE.txt in this directory.",
          "const Node nodes[] = {"]
output += [f"  {{0x{node['cp']:X}, {node['first'] if node['children'] else 0}, "
           f"{len(node['children'])}, {node['glyph']}}}," for node in nodes]
output += ["};", "const uint16_t glyphRows[][10] = {"]
output += ["  {" + ",".join(f"0x{row:03X}" for row in rows) + "}," for rows in glyphs]
output += ["};", f"const size_t nodeCount = {len(nodes)};",
           f"const size_t glyphCount = {len(glyphs)};", f"const size_t sequenceCount = {len(sequences)};", ""]
args.output.mkdir(parents=True, exist_ok=True)
(args.output / "OpenMojiData.inc").write_text("\n".join(output), encoding="ascii", newline="\n")
report = {"source": "OpenMoji 17.0.0 black SVG", "license": "CC BY-SA 4.0",
          "archive_sha256": expected, "metadata_sha256": hashlib.sha256(args.metadata.read_bytes()).hexdigest(),
          "color_fallback_archive_sha256": color_sha, "color_fallback_glyphs": ["1F195"],
          "rasterization": "Sharp 72px; ink crop; 3px maximum filter; Lanczos 10px; threshold 80",
          "sequence_count": len(sequences), "unique_bitmaps": len(glyphs), "trie_nodes": len(nodes),
          "max_codepoints": max(map(len, sequences)), "bitmap_size": "10x10, 1 bit",
          "estimated_flash_bytes": len(nodes)*12 + len(glyphs)*20,
          "generated_hash_line_endings": "LF",
          "generated_sha256": hashlib.sha256((args.output / "OpenMojiData.inc").read_text(encoding="ascii").encode("ascii")).hexdigest()}
(args.output / "manifest.json").write_text(json.dumps(report, indent=2) + "\n")
print(json.dumps(report, indent=2))
